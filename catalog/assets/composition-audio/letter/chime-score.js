/* 原创风铃小品；页面、检查和试听共用同一份乐谱。 */
(() => {
  'use strict';
  function createScore({sendAt,firstSettle,loopStart,waterLead,loopDuration=9}){
    const beat=loopDuration/12,start=Math.max(sendAt+waterLead,firstSettle-6*beat),events=[];
    const add=(time,pitch,gain,role,pan)=>events.push({
      time,kind:'leafTouch',duration:.95,pitch,gain,pan,panTo:pan,role
    });
    // 四句三拍子的主题：上扬、应答、落定时的高点、回到主音。
    const melody=[
      [0,4,.76],[.5,7,.58],[1,9,.88],[2,7,.62],
      [3,4,.72],[4,2,.5],[4.5,4,.56],[5,7,.68],
      [6,9,.96],[6.5,7,.68],[7,4,.63],[8,2,.43],
      [9,4,.65],[10,7,.52],[10.5,2,.39],[11,0,.66]
    ];
    for(const [at,pitch,gain] of melody)add(start+at*beat,pitch,gain,'melody',-.08);
    // 伴奏只在主句之间轻点，声场略偏右，不跟着每件物品横跳。
    const accompaniment=[
      [.25,0,.2],[1.5,4,.24],[2.5,0,.19],
      [3.25,0,.18],[3.75,4,.2],[4.75,0,.17],[5.5,4,.23],
      [6.25,0,.24],[7.5,7,.18],[8.5,4,.16],
      [9.5,0,.18],[10.25,4,.14]
    ];
    for(const [at,pitch,gain] of accompaniment)add(start+at*beat,pitch,gain,'accompaniment',.32);
    // 银河徐徐亮起时留出呼吸，用下降的三音结束主段。
    const bridgeStart=start+12*beat+.5,bridgeEnd=loopStart-1.2;
    if(bridgeEnd-bridgeStart>1.5){
      for(const [i,pitch] of [4,2,0].entries()){
        add(bridgeStart+(bridgeEnd-bridgeStart)*i/2,pitch,[.34,.27,.3][i],'bridge',-.04);
      }
    }
    // 星空留下以后仍是一首有发展的小品。八段各四小节，用同一动机问答，
    // 中间留白后再生长；段落之间允许余音交叠，仅在整曲回跳前收完。
    const nightMelody=[
      // 主题重新出现：E–G–A，是进入星空时可以认出的那句话。
      [[0,4,.65],[.5,7,.5],[1,9,.78],[2,7,.56],
        [3,4,.64],[4,2,.46],[4.5,4,.52],[5,7,.63],
        [6,9,.8],[7,7,.61],[7.5,4,.48],[8.5,2,.43],
        [9,4,.61],[10,7,.56],[11,4,.47]],
      // 回答：往下走，长短句交替，不把每拍都填满。
      [[0,2,.56],[1,4,.61],[2,7,.68],
        [3.5,4,.51],[4,2,.44],[5,0,.55],
        [6.5,2,.56],[7,4,.65],[8,7,.7],
        [9.5,4,.51],[10,2,.44],[11,0,.58]],
      // 流动：用短的五声琶音连接长音，逐渐明亮。
      [[0,0,.55],[.5,2,.45],[1,4,.64],[2,7,.69],
        [3,4,.6],[3.5,7,.52],[4,9,.76],[5,7,.59],
        [6,2,.56],[6.5,4,.5],[7,7,.69],[8,9,.82],
        [9,7,.65],[9.5,4,.5],[10,2,.46],[11,4,.62]],
      // 展开：高音作回答，轻点更密，但主句仍有清晰重心。
      [[0,7,.73],[.5,9,.61],[1,7,.68],[2,4,.57],
        [3,9,.87],[3.5,7,.64],[4,4,.57],[4.5,7,.54],[5.5,9,.79],
        [6,7,.69],[6.75,4,.5],[7.5,2,.48],[8,4,.66],
        [9,7,.74],[9.5,4,.53],[10.5,2,.46],[11.5,0,.61]],
      // 留白：降低密度而不一路变小，为下一次展开保留呼吸。
      [[0,4,.58],[1.5,7,.53],[3,9,.67],
        [4.5,7,.49],[6,4,.57],[7.5,2,.46],[9,0,.58],[11,2,.5]],
      // 再生长：恢复动机，末句向上接入全曲高点。
      [[0,4,.63],[.5,7,.5],[1,9,.76],[2.5,7,.57],
        [3,4,.61],[4,2,.45],[4.5,4,.53],[5,7,.66],
        [6,4,.62],[6.5,7,.54],[7,9,.81],[8,7,.63],
        [9,2,.55],[9.5,4,.58],[10,7,.72],[11,9,.85]],
      // 高点：记忆动机与短回答交织，音量和密度在这里最丰富。
      [[0,4,.72],[.5,7,.6],[1,9,.94],[1.75,7,.66],[2.5,4,.56],
        [3,7,.77],[3.5,9,.69],[4,7,.72],[5,4,.57],
        [6,9,.91],[6.5,7,.67],[7,4,.6],[7.5,2,.49],[8.25,4,.59],
        [9,7,.78],[9.5,9,.66],[10,7,.71],[10.75,4,.54],[11.5,2,.49]],
      // 回环：带着旋律收回 C，循环重来时自然接到第一段 E。
      [[0,4,.67],[.5,7,.53],[1,9,.76],[2,7,.58],
        [3,4,.63],[4,2,.46],[4.5,4,.5],[5,7,.61],
        [6,4,.6],[7,2,.46],[7.5,0,.54],[8.5,2,.44],
        [9,4,.58],[10.5,0,.62]]
    ];
    // 伴奏以 C/E/G 作轻回应，与主旋律错开落点，疏密随乐句起伏。
    const nightAccompaniment=[
      [[.25,0,.19],[1.5,4,.21],[2.5,0,.17],[3.75,7,.18],
        [5.5,4,.21],[6.5,0,.23],[8,7,.16],[9.5,0,.2],[10.5,4,.17]],
      [[.5,0,.16],[2.5,4,.19],[4.75,7,.14],[5.5,4,.17],
        [7.5,0,.2],[8.75,4,.15],[10.5,7,.15],[11.5,4,.18]],
      [[.25,7,.18],[1.5,0,.2],[2.75,4,.17],[4.5,0,.22],
        [5.5,4,.18],[6.25,0,.2],[7.5,4,.21],[8.5,0,.24],
        [9.75,7,.17],[10.5,0,.2],[11.5,7,.18]],
      [[.25,0,.22],[1.5,4,.2],[2.75,7,.17],[3.25,0,.25],
        [4.75,4,.19],[6.25,0,.22],[7,7,.17],[8.5,0,.21],
        [9.25,4,.23],[10,7,.16],[11,4,.18]],
      [[.75,0,.15],[3.75,4,.17],[6.75,0,.15],[9.75,4,.16]],
      [[.25,0,.19],[1.75,4,.18],[3.5,0,.19],[5.5,4,.2],
        [6.25,0,.22],[7.5,4,.22],[8.5,0,.19],[9.75,7,.18],
        [10.5,4,.22],[11.5,0,.24]],
      [[.25,0,.24],[1.375,4,.26],[2.125,0,.2],[3.25,4,.25],
        [4.5,0,.22],[5.5,7,.18],[6.25,0,.26],[7.25,7,.19],
        [8.625,0,.2],[9.25,4,.24],[10.375,0,.2],[11.25,7,.17]],
      [[.25,0,.2],[1.5,4,.21],[2.5,0,.17],[3.5,7,.17],
        [5.5,0,.2],[6.5,7,.16],[8,4,.15],[9.5,7,.14]]
    ];
    for(let section=0;section<nightMelody.length;section++){
      const sectionStart=loopStart+section*loopDuration;
      for(const [at,pitch,gain] of nightMelody[section]){
        add(sectionStart+at*beat,pitch,gain,'coda',-.08);
      }
      for(const [at,pitch,gain] of nightAccompaniment[section]){
        add(sectionStart+at*beat,pitch,gain,'coda-accompaniment',.32);
      }
    }
    return events.sort((a,b)=>a.time-b.time);
  }
  const music={createScore,sustainDuration:72};
  if(typeof module!=='undefined'&&module.exports)module.exports=music;
  else globalThis.StarLetterMusic=music;
})();
